macro_rules! test_what_encrypting_leaves {
    (
        $(#[$gate:meta])*
        $found:ident, $leaves:ident, $refused:ident,
        $algorithm:expr, $key:expr, $nonce:expr, $plaintext:expr, $ciphertext:expr $(,)?
    ) => {
        $(#[$gate])*
        #[test]
        fn $found() -> Result<(), AnyError> {
            let mut watch = Forensics::watching(&backwards(&$ciphertext))?;

            let aead = Aead::from_algorithm($algorithm);
            let mut key = holding(&$key);
            let mut tag = vec![0_u8; aead.tag_size()];

            forensics!({
                // Leaked and not a local: any call after the capture may write
                // over what a buffer let go of, and then the sweep genuinely
                // does not find what the operation wrote there.
                let data = holding(&$plaintext).leak();

                capture(|| aead.encrypt(&key, &$nonce, AAD, data, &mut tag))?;

                key.fast_zeroize();
            });

            is_found(&watch.snapshot()?, "a message sealed through the facade, and kept");

            Ok(())
        }

        $(#[$gate])*
        #[test]
        fn $leaves() -> Result<(), AnyError> {
            let mut watching = Watching::start(&[("key", &$key), ("plaintext", &$plaintext)])?;

            let aead = Aead::from_algorithm($algorithm);
            let mut key = holding(&$key);
            let mut data = holding(&$plaintext);
            let mut tag = vec![0_u8; aead.tag_size()];

            forensics!({
                capture(|| aead.encrypt(&key, &$nonce, AAD, &mut data, &mut tag))?;

                // CORRECTNESS: after the capture. A call made before it writes
                // over the stack and the registers the operation left, and
                // then the absence below is about that call and not about the
                // operation.
                //
                // The key is the caller's. The buffer holds the ciphertext
                // and the tag is public, so both stay.
                key.fast_zeroize();
            });

            watching.none_left("encrypting through the facade")?;

            Ok(())
        }

        /// The key is converted before the nonce is, so it has been read
        /// when the width is refused.
        $(#[$gate])*
        #[test]
        fn $refused() -> Result<(), AnyError> {
            let mut watching = Watching::start(&[("key", &$key), ("plaintext", &$plaintext)])?;

            let aead = Aead::from_algorithm($algorithm);
            let mut key = holding(&$key);
            let mut data = holding(&$plaintext);
            let mut tag = vec![0_u8; aead.tag_size()];

            forensics!({
                let refused = capture(|| {
                    aead.encrypt(&key, &$nonce[1..], AAD, &mut data, &mut tag)
                });

                assert!(
                    matches!(refused, Err(AeadError::NonceWidth { .. })),
                    "a nonce of the wrong width was not refused: {refused:?}"
                );

                // CORRECTNESS: after the capture. A call made before it writes
                // over the stack and the registers the operation left, and
                // then the absence below is about that call and not about the
                // operation.
                //
                // The key and the plaintext, which nothing sealed, are the
                // caller's.
                key.fast_zeroize();
                data.fast_zeroize();
            });

            watching.none_left("encrypting under a nonce of the wrong width")?;

            Ok(())
        }
    };
}

