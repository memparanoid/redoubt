/// The key in a box, so no stack slot is left holding it.
pub(crate) fn a_key() -> Box<[u8; KEY_SIZE]> {
    let mut key = Box::new([0_u8; KEY_SIZE]);

    giving(&mut *key, &KEY);

    key
}

/// A buffer holding `what`, for an operation to work on where it lies.
pub(crate) fn holding(what: &[u8]) -> Vec<u8> {
    let mut data = vec![0_u8; what.len()];

    giving(&mut data, what);

    data
}
