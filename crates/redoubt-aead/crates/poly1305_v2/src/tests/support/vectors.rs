//! RFC 8439 Appendix A.3, all eleven.
//!
//! Numbers five to eleven are the reason the appendix is worth transcribing
//! whole: each one was written against a specific way of getting the reduction
//! wrong, and the appendix says which in a sentence. Those sentences are the
//! `asks` field, so a failure names the mistake instead of a number.

use redoubt_aead_core::consts::poly1305::{KEY_SIZE, TAG_SIZE};

/// One row of the appendix.
pub(crate) struct Vector {
    /// Which one it is there, so a failure here can be read against it.
    pub(crate) number: u8,
    /// What it was written to catch.
    pub(crate) asks: &'static str,
    /// `r` in the first sixteen bytes, `s` in the rest.
    pub(crate) key: [u8; KEY_SIZE],
    /// What is authenticated.
    pub(crate) message: &'static [u8],
    /// What comes out.
    pub(crate) tag: [u8; TAG_SIZE],
}

