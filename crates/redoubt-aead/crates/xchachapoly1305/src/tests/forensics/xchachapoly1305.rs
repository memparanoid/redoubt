/// The tag `PLAINTEXT` is sealed with, and the one a decrypt of `CIPHERTEXT`
/// computes: public once sent, but on a refusal it is the valid tag of a
/// message somebody sent without one, which is what a forgery needs.
const TAG: [u8; TAG_SIZE] = [
    0x62, 0xB1, 0x55, 0x9B, 0x28, 0x18, 0xEC, 0x25, 0xC4, 0xCD, 0xCD, 0x07, 0x86, 0x38, 0xE1, 0xA8,
];

/// A tag sharing no run with `TAG`. The near miss, one bit turned over, would
/// sit in the caller's memory as fifteen bytes of the needle.
const WRONG: [u8; TAG_SIZE] = [
    0x84, 0x1D, 0xA6, 0x3F, 0xD8, 0x60, 0x95, 0x2E, 0xBB, 0x07, 0x4C, 0xE1, 0x76, 0xAF, 0x13, 0xCA,
];

/// The one-time key: the first thirty-two bytes of the keystream under `KEY`
/// and `XNONCE`. Its high half is the authenticator's pad, kept as it is.
const OTK: [u8; POLY_KEY_SIZE] = [
    0xC7, 0x24, 0x98, 0xE6, 0xDA, 0x10, 0x58, 0x64, 0x9F, 0xC6, 0x5E, 0x51, 0x28, 0xF8, 0x3D, 0x16,
    0x43, 0xAB, 0x0F, 0x83, 0x2F, 0x14, 0x8B, 0xE3, 0xA4, 0x18, 0xC8, 0x79, 0xF9, 0x50, 0x86, 0x7D,
];

/// `r` as an authenticator keyed with `OTK` holds it: five clamped limbs of
/// twenty-six bits, cut after the last byte that is not zero, which any empty
/// memory would match.
const R: [u8; 19] = [
    0xC7, 0x24, 0x98, 0x02, // limb 0 = 0x298_24C7
    0x01, 0x36, 0x04, 0x02, // limb 1 = 0x204_3601
    0x45, 0xC0, 0x69, 0x00, // limb 2 = 0x69_C045
    0x7B, 0x05, 0xA0, 0x00, // limb 3 = 0xA0_057B
    0xF8, 0x3D, 0x06, // limb 4 = 0x6_3DF8
];

/// The accumulator once `tag_with` has told the authenticator `AAD`,
/// `CIPHERTEXT` and their lengths; cut the same way.
const ACC: [u8; 36] = [
    0x1F, 0x06, 0x46, 0x00, 0x00, 0x00, 0x00, 0x00, // limb 0 = 0x46_061F
    0x46, 0xFE, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, // limb 1 = 0x40_FE46
    0x26, 0xF4, 0x51, 0x03, 0x00, 0x00, 0x00, 0x00, // limb 2 = 0x351_F426
    0x16, 0x38, 0x32, 0x02, 0x00, 0x00, 0x00, 0x00, // limb 3 = 0x232_3816
    0xE7, 0x5A, 0x2B, 0x03, // limb 4 = 0x32B_5AE7
];

/// The key in a box, so no stack slot is left holding it.
fn a_key() -> Box<[u8; KEY_SIZE]> {
    let mut key = Box::new([0_u8; KEY_SIZE]);

    giving(&mut *key, &KEY);

    key
}

/// A one-time key holding `OTK`, as `one_time_key` would have left it.
fn a_one_time_key() -> OneTimeKey {
    let mut one_time_key = OneTimeKey::from_default();

    giving(one_time_key.as_mut_array(), &OTK);

    one_time_key
}

/// A buffer holding `what`, for an operation to work on where it lies.
fn holding(what: &[u8]) -> Vec<u8> {
    let mut data = vec![0_u8; what.len()];

    giving(&mut data, what);

    data
}

