#[test]
fn test_decrypting_under_a_wrong_tag_leaves_nothing() -> Result<(), AnyError> {
    let mut watching = Watching::start(&[
        ("key", &KEY),
        ("plaintext", &PLAINTEXT),
        ("one-time key", &OTK),
        ("r", &R),
        ("accumulator", &ACC),
        ("tag", &TAG),
    ])?;

    let mut key = a_key();
    let mut data = holding(&CIPHERTEXT);

    forensics!({
        let mut aead = XChaCha20Poly1305::new();

        let refused = capture(|| aead.decrypt(&key, &XNONCE, AAD, &mut data, &WRONG));

        assert_eq!(refused, Err(AeadCoreError::AuthenticationFailed));

        // CORRECTNESS: after the capture. A call made before it writes over the
        // stack and the registers the operation left, and then the absence
        // below is about that call and not about the operation.
        //
        // The buffer is not emptied here: that is the refusal's to do, and
        // emptying it here would keep this absence green without it.
        key.fast_zeroize();
    });

    watching.none_left("decrypting under a wrong tag")?;

    Ok(())
}
