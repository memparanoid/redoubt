#[test]
fn test_what_one_time_key_wrote_is_found_while_the_caller_holds_it() -> Result<(), AnyError> {
    let mut watch = Forensics::watching(&backwards(&OTK))?;

    let mut key = a_key();

    forensics!({
        let aead = XChaCha20Poly1305::new();

        // Leaked and not a local: any call after the capture may write over
        // what a buffer let go of, and then the sweep genuinely does not find
        // what the operation wrote there.
        let out = Box::leak(Box::new(OneTimeKey::from_default()));

        capture(|| aead.one_time_key(&key, &XNONCE, out));

        key.fast_zeroize();
    });

    is_found(&watch.snapshot()?, "a one-time key derived, and kept");

    Ok(())
}

#[test]
fn test_one_time_key_leaves_nothing() -> Result<(), AnyError> {
    let mut watching = Watching::start(&[("key", &KEY), ("one-time key", &OTK)])?;

    let mut key = a_key();

    forensics!({
        let aead = XChaCha20Poly1305::new();
        let mut out = OneTimeKey::from_default();

        capture(|| aead.one_time_key(&key, &XNONCE, &mut out));

        // CORRECTNESS: after the capture. A call made before it writes over the
        // stack and the registers the operation left, and then the absence
        // below is about that call and not about the operation.
        //
        // The key and the one-time key are the caller's.
        key.fast_zeroize();
        out.fast_zeroize();
    });

    watching.none_left("one_time_key")?;

    Ok(())
}

