#[test]
fn test_decrypting_leaves_nothing() -> Result<(), AnyError> {
    let mut watching = Watching::start(&[
        ("key", &KEY),
        ("plaintext", &PLAINTEXT),
        ("tag", &SEALED_TAG),
    ])?;

    let mut key = a_key();
    let mut data = holding(&CIPHERTEXT);
    let mut given = [0_u8; TAG_SIZE];

    giving(&mut given, &SEALED_TAG);

    forensics!({
        let mut aead = Aegis128L::new();

        capture(|| aead.decrypt(&key, &NONCE, AAD, &mut data, &given))?;

        // CORRECTNESS: after the capture. A call made before it writes over the
        // stack and the registers the operation left, and then the absence
        // below is about that call and not about the operation.
        //
        // The plaintext, the key and the tag handed in are the caller's.
        data.fast_zeroize();
        key.fast_zeroize();
        given.fast_zeroize();
    });

    watching.none_left("decrypting")?;

    Ok(())
}

#[test]
fn test_decrypting_under_a_wrong_tag_leaves_nothing() -> Result<(), AnyError> {
    let mut watching = Watching::start(&[
        ("key", &KEY),
        ("plaintext", &PLAINTEXT),
        ("tag", &SEALED_TAG),
    ])?;

    let mut key = a_key();
    let mut data = holding(&CIPHERTEXT);

    forensics!({
        let mut aead = Aegis128L::new();

        let refused = capture(|| aead.decrypt(&key, &NONCE, AAD, &mut data, &WRONG));

        assert_eq!(refused, Err(AeadCoreError::AuthenticationFailed));

        // CORRECTNESS: after the capture. A call made before it writes over the
        // stack and the registers the operation left, and then the absence
        // below is about that call and not about the operation.
        //
        // The buffer is not emptied here: that is the refusal's to do, and
        // emptying it here would keep this absence green without it.
        key.fast_zeroize();
    });

    watching.none_left("decrypting under a wrong tag")?;

    Ok(())
}
