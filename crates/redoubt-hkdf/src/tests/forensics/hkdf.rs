#[test]
fn test_deriving_more_than_the_counter_has_blocks_for_leaves_nothing() -> Result<(), AnyError> {
    let mut watch = Forensics::watching(&ikm_backwards())?;

    let report_before = watch.snapshot()?;

    let mut ikm = an_ikm();

    forensics!({
        let mut okm = vec![0_u8; MAX_OUTPUT_SIZE + 1];
        let derivation = HkdfSha256::new();

        let refused = capture(|| derivation.derive(SALT, &*ikm, INFO, &mut okm));

        assert_eq!(refused, Err(HkdfError::OutputTooLong));

        // CORRECTNESS: after the capture. A call made before it writes over the
        // stack and the registers the operation left, and then the absence
        // below is about that call and not about the operation.
        ikm.fast_zeroize();
    });

    leaves_nothing(
        &report_before,
        "nothing held yet",
        &watch.snapshot()?,
        "deriving more than the counter has blocks for",
    );

    Ok(())
}

