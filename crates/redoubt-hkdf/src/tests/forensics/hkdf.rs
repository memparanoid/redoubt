macro_rules! deriving {
    ($($found:ident, $absent:ident: $len:expr;)*) => {
        $(
            #[test]
            fn $found() -> Result<(), AnyError> {
                let mut watch = Forensics::watching(&okm_backwards())?;

                let mut ikm = an_ikm();

                forensics!({
                    let derivation = HkdfSha256::new();

                    // Leaked and not a local: any call after the capture may
                    // write over what a buffer let go of, and then the sweep
                    // genuinely does not find what the operation wrote there.
                    let okm = vec![0_u8; $len].leak();

                    capture(|| derivation.derive(SALT, &*ikm, INFO, okm))?;

                    // What it read, emptied: what is found is what it wrote.
                    ikm.fast_zeroize();
                });

                is_found(&watch.snapshot()?, concat!("an output of ", $len, " derived, and kept"));

                Ok(())
            }

            #[test]
            fn $absent() -> Result<(), AnyError> {
                let mut ikm_watch = Forensics::watching(&ikm_backwards())?;
                let mut okm_watch = Forensics::watching(&okm_backwards())?;

                let ikm_before = ikm_watch.snapshot()?;
                let okm_before = okm_watch.snapshot()?;

                let mut ikm = an_ikm();

                forensics!({
                    let mut okm = vec![0_u8; $len];
                    let derivation = HkdfSha256::new();

                    capture(|| derivation.derive(SALT, &*ikm, INFO, &mut okm))?;

                    // CORRECTNESS: after the capture. A call made before it
                    // writes over the stack and the registers the operation
                    // left, and then the absence below is about that call and
                    // not about the operation.
                    okm.fast_zeroize();
                    ikm.fast_zeroize();
                });

                leaves_nothing(
                    &ikm_before,
                    "nothing held yet",
                    &ikm_watch.snapshot()?,
                    concat!("deriving ", $len, " bytes, of what it read"),
                );
                leaves_nothing(
                    &okm_before,
                    "nothing held yet",
                    &okm_watch.snapshot()?,
                    concat!("deriving ", $len, " bytes, of what it wrote"),
                );

                Ok(())
            }
        )*
    };
}

