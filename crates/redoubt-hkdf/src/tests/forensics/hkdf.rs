/// The key material's needle, built from its last byte to its first and never
/// turned around: the forward bytes must not exist in this process.
fn ikm_backwards() -> Vec<u8> {
    IKM.iter().rev().copied().collect()
}

/// The output's needle, built the same way and for the same reason.
fn okm_backwards() -> Vec<u8> {
    OKM.iter().rev().copied().collect()
}

/// The key material in a box, through the copy that erases what it used: a
/// compiler move would leave residue the test caused itself.
fn an_ikm() -> Box<[u8; 32]> {
    let mut ikm = Box::new([0_u8; 32]);

    // SAFETY: both are thirty-two bytes, and a constant and a heap block are
    // different allocations.
    unsafe { redoubt_mem::copy_nonoverlapping(IKM.as_ptr(), ikm.as_mut_ptr(), IKM.len()) };

    ikm
}

